function tf = events_current(data)
%EVENTS_CURRENT True only after successful calculation for the live selection.
%   The selection (data.behav.selection) is kept in sync by the Behavior viewer.
tf = data.has('behav') && isfield(data.behav, 'eventsValid') && data.behav.eventsValid ...
    && isfield(data.behav, 'eventsBodypart') && isfield(data.behav, 'eventsTrace') ...
    && isfield(data.behav, 'selection') ...
    && isequal(data.behav.eventsBodypart, data.behav.selection.bodypart) ...
    && strcmp(data.behav.eventsTrace, data.behav.selection.trace);
end
